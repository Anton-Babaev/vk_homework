package main

import "fmt"

// N — размер доски (N x N).
const n = 8

func main() {
	// Внешний цикл — строки доски
	for i := 0; i < n; i++ {
		// Внутренний цикл — столбцы доски
		for j := 0; j < N; j++ {
			// Шахматный порядок: если сумма индексов чётная — "#",
			// иначе — пробел.
			if (i+j)%2 == 0 {
				fmt.Print(" ")
			} else {
				fmt.Print("#")
			}
		}
		// После каждой строки — перенос.
		fmt.Println()
	}
}
